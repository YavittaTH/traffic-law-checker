_COMPILED = [(re.compile(p), w) for p, w in TERMS]


def expansions(query: str) -> list[str]:
    q = query.lower()
    return list(dict.fromkeys(w for p, w in _COMPILED if p.search(q)))


def expand(query: str) -> str:
    extra = expansions(query)
    return query if not extra else query + " " + " ".join(extra)
